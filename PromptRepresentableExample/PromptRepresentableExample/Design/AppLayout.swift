import Foundation

/// Shared layout constants, so every screen in the example uses the same rhythm.
enum AppLayout {
    /// Spacing between tightly related pieces of text, such as a title and its subtitle.
    static let tightSpacing: Double = 4

    /// Spacing between distinct rows inside a section.
    static let rowSpacing: Double = 8

    /// Spacing between groups of content.
    static let groupSpacing: Double = 16
}
